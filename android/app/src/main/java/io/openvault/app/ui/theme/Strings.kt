    AppLanguage.ENGLISH -> EnglishStrings
    AppLanguage.VIETNAMESE -> VietnameseStrings
}

val LocalStrings = staticCompositionLocalOf { EnglishStrings }

/**
 * Parses an ISO-8601 UTC timestamp from Cloudflare D1 and converts it cleanly to the
 * device's local timezone (e.g., ICT / GMT+7), formatted according to the selected app language.
 */
fun formatLocalTimestamp(isoString: String, isVi: Boolean): String {
    val trimmed = isoString.trim()
    if (trimmed.isEmpty()) return ""
    val instant = runCatching { Instant.parse(trimmed) }.getOrNull()
        ?: runCatching { OffsetDateTime.parse(trimmed).toInstant() }.getOrNull()
        ?: runCatching { Instant.parse(trimmed.replace(' ', 'T') + "Z") }.getOrNull()
        ?: return trimmed.take(19).replace('T', ' ')

    val localZdt = instant.atZone(ZoneId.systemDefault())
    return if (isVi) {
        val viLocale = Locale.forLanguageTag("vi-VN")
        val dayName = DateTimeFormatter.ofPattern("EEEE", viLocale).format(localZdt)
            .replaceFirstChar { it.uppercaseChar() }
        val rest = DateTimeFormatter.ofPattern("d 'tháng' M, yyyy HH:mm:ss", viLocale).format(localZdt)
        "$dayName, $rest"
    } else {
        val enLocale = Locale.ENGLISH
        DateTimeFormatter.ofPattern("EEEE, MMM d, yyyy HH:mm:ss", enLocale).format(localZdt)
    }
}
